function openTNPSCStudy(subject, language = "ta") {
  
const area = document.getElementById("content");

if (!area) return;

document.querySelectorAll("main > *:not(#content)").forEach(el => {
  el.style.setProperty("display", "none", "important");
});

const lessons = tnpscLessons[subject];


  if (!area) return;

  if (!lessons) {
    area.innerHTML = `
      <div class="card">
        <h2>Study Materials / பாடங்கள்</h2>
        <p>Choose a subject / பாடத்தைத் தேர்வு செய்யவும்</p>
        ${Object.keys(tnpscLessons).map(s =>
          `<button style="width:100%;margin:5px 0"
          onclick="openTNPSCStudy('${s}','${language}')">${s}</button>`
        ).join("")}
      </div>`;
    area.scrollIntoView({behavior:"smooth"});
    return;
  }

  area.innerHTML = `
    <div class="card">
      <button onclick="closeTNPSCStudy()">
  ← Back / பின்செல்
</button>
      <h2>${subject}</h2>
      ${lessons.map((lesson,index) => `
        <div style="background:#f2f5fa;padding:15px;border-radius:12px;margin:12px 0">
          <h3>${lesson.title}</h3>
          <p>${language === "ta" ? lesson.ta : lesson.en}</p>
          <strong>${language === "ta" ? "முக்கிய குறிப்புகள்" : "Important Points"}</strong>
          <ul>
            ${lesson.points.map(p => `<li>${p}</li>`).join("")}
          </ul>
        </div>
      `).join("")}
    </div>`;

  area.scrollIntoView({behavior:"smooth"});
}
function closeTNPSCStudy() {
  const area = document.getElementById("content");

  Array.from(area.parentElement.children).forEach(el => {
    el.style.display = "";
  });

  area.innerHTML = "";
  window.scrollTo({ top: 0, behavior: "smooth" });
}